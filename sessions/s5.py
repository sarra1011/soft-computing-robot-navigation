"""Session 5 - frozen, reproducible comparison on the TEST maps D, E, F.

Protocol: the systems were frozen on A/B/C. Same maps, initial states, step,
stopping criteria and noise realisations (seeds 0..19, 2 400 pre-generated
triplets each) for every controller. 1 nominal + 20 noisy runs per pair.
"""
from __future__ import annotations

import math

import matplotlib.pyplot as plt
import numpy as np

from controllers import METHODS, make_controller
from metrics import aggregate, write_csv, write_summary_csv
from plots import col, plot_comparison
from scenarios import SCENARIOS
from sessions.common import banner, done, fmt_ms

TEST = ("D", "E", "F")
SYSTEMS = ("sys-v1", "sys-v2")


def run_campaign(ctx, systems=SYSTEMS, methods=METHODS, scenarios=TEST, label="s5",
                 builders=None, log=True):
    """Generic campaign; `builders` maps name -> callable() returning a controller."""
    p = ctx.params
    builders = builders or {f"{m}|{s}": (lambda m=m, s=s: make_controller(m, p, s))
                            for s in systems for m in methods}
    metrics, nominal, noisy = [], {}, {}
    for key, build in builders.items():
        for sid in scenarios:
            sc = SCENARIOS[sid]
            logdir = ctx.logs / label if log else None
            r, m = ctx.run(sc, build(), log_dir=logdir)
            nominal[(key, sid)] = r
            metrics.append(m)
            noisy[(key, sid)] = []
            for s in ctx.seeds:
                rn, mn = ctx.run(sc, build(), seed=s, log_dir=logdir)
                noisy[(key, sid)].append(rn)
                metrics.append(mn)
            ok = sum(x["success"] for x in metrics[-len(ctx.seeds):])
            print(f"  {key:22s} {sid}: nominal {m['status']:9s} noisy {ok:2d}/{len(ctx.seeds)} arrivals")
    return metrics, nominal, noisy


def run(ctx):
    t0 = banner("SESSION 5 - comparative campaign on test maps D, E, F")
    p = ctx.params
    metrics, nominal, noisy = run_campaign(ctx)
    ctx.campaign = (nominal, noisy)
    write_summary_csv(metrics, ctx.results / "s5_episodes.csv")
    agg = aggregate(metrics)
    write_csv(agg, ctx.results / "s5_aggregate.csv")
    md = tables_markdown(agg, ctx)
    (ctx.results / "s5_tables.md").write_text(md, encoding="utf-8")
    print(md)
    for sysv in SYSTEMS:
        for sid in TEST:
            res = {m: nominal[(f"{m}|{sysv}", sid)] for m in METHODS}
            nz = {m: noisy[(f"{m}|{sysv}", sid)] for m in METHODS}
            sc = SCENARIOS[sid]
            plot_comparison(res, sc, p, ctx.figs / f"s5_{sid}_{sysv}.png",
                            f"Session 5 - test scenario {sid} ({sc.description}) - {sysv} - {p.version} - "
                            f"bold nominal, thin {len(ctx.seeds)} noisy seeds", nz)
    plot_success(ctx, agg)
    plot_compute_time(ctx, nominal)
    plot_metric_boxes(ctx, metrics)
    noise_ranking(ctx, agg)
    ctx.campaign_agg = agg
    done(t0)
    return metrics


def tables_markdown(agg, ctx):
    n = len(ctx.seeds)
    out = [f"# Session 5 - results on the test maps (generated by run_experiments.py)\n",
           f"Noisy runs: seeds 0..{n - 1} (N = {n}); sigma_xy = 0.02 m, sigma_theta = 0.02 rad. "
           "Time and length: mean ± std over SUCCESSFUL noisy runs, (n) = number of successes used. "
           "Guard: real minimum over the path segments, mean ± std over all runs (worst case). "
           "Compute: median / p95 of the per-decision time, microseconds, on this machine.\n",
           "The classic system uses exactly the Sugeno avoidance: the comparison mostly concerns "
           "the goal law, and Mamdani vs Sugeno in avoidance.\n"]
    for sysv in SYSTEMS:
        for sid in TEST:
            out.append(f"\n## Scenario {sid} - {sysv}\n")
            out.append("| Method | Nominal | Success / N | Collisions / N | Timeouts | Blocked | "
                       "Mean time [s] | Mean L [m] | Min guard [m] (worst) | sum abs dv | "
                       "sum abs domega | Compute med / p95 [us] | Prev. stops | Switches |")
            out.append("|" + "---|" * 14)
            for meth in METHODS:
                key = f"{meth}"
                nom = [a for a in agg if a["scenario"] == sid and a["controller"] == meth
                       and a["condition"] == "nominal" and a["system"] == sysv]
                noi = [a for a in agg if a["scenario"] == sid and a["controller"] == meth
                       and a["condition"] == "noisy" and a["system"] == sysv]
                if not noi:
                    continue
                a, b = noi[0], nom[0]
                nom_s = f"{b['T_mean']:.2f} s" if b["success"] else ("collision" if b["collision"] else "timeout")
                out.append(
                    f"| {key} | {nom_s} | {a['success']}/{a['N']} | {a['collision']}/{a['N']} | "
                    f"{a['timeout']} | {a['blocked']} | {fmt_ms(a['T_mean'], a['T_std'], a['n_used'])} | "
                    f"{fmt_ms(a['L_mean'], a['L_std'], a['n_used'])} | "
                    f"{a['min_guard_mean']:.3f} ± {a['min_guard_std']:.3f} ({a['min_guard_worst']:.3f}) | "
                    f"{a['sum_dv_mean']:.1f} | {a['sum_domega_mean']:.1f} | "
                    f"{a['t_compute_median_us']:.0f} / {a['t_compute_p95_us']:.0f} | "
                    f"{a['preventive_stops']} | {a['mode_switches_mean']:.0f} |")
    return "\n".join(out) + "\n"


def plot_success(ctx, agg):
    fig, axs = plt.subplots(1, 2, figsize=(14, 4.5), sharey=True)
    for ax, sysv in zip(axs, SYSTEMS):
        x = np.arange(len(TEST))
        w = 0.26
        for i, meth in enumerate(METHODS):
            s = [next((a["success"] for a in agg if a["scenario"] == sid and a["controller"] == meth
                       and a["condition"] == "noisy" and a["system"] == sysv), 0) for sid in TEST]
            c = [next((a["collision"] for a in agg if a["scenario"] == sid and a["controller"] == meth
                       and a["condition"] == "noisy" and a["system"] == sysv), 0) for sid in TEST]
            ax.bar(x + (i - 1) * w, s, w, color=col(meth), label=f"{meth} arrivals")
            ax.bar(x + (i - 1) * w, c, w, bottom=s, color=col(meth), alpha=0.35, hatch="//",
                   label=f"{meth} collisions")
            for xi, si in zip(x + (i - 1) * w, s):
                ax.text(xi, si + 0.2, str(si), ha="center", fontsize=8)
        ax.set_xticks(x); ax.set_xticklabels([f"scenario {s}" for s in TEST])
        ax.axhline(len(ctx.seeds), color="k", lw=0.6, ls=":")
        ax.set_title(f"{sysv}"); ax.set_ylabel(f"runs out of {len(ctx.seeds)} (noisy)")
    axs[1].legend(fontsize=7, ncol=3, loc="lower right")
    fig.suptitle(f"Session 5 - arrivals and collisions on the test maps, {len(ctx.seeds)} noisy seeds - "
                 f"{ctx.params.version}")
    fig.tight_layout(rect=(0, 0, 1, 0.93))
    fig.savefig(ctx.figs / "s5_success.png", dpi=150)
    plt.close(fig)


def plot_compute_time(ctx, nominal):
    data, labels, colors = [], [], []
    for meth in METHODS:
        for sysv in SYSTEMS:
            tc = np.concatenate([[r["t_compute"] for r in nominal[(f"{meth}|{sysv}", sid)].rows
                                  if r["status"] == "running"] for sid in TEST]) * 1e6
            data.append(tc); labels.append(f"{meth}\n{sysv}"); colors.append(col(meth))
    fig, ax = plt.subplots(figsize=(11, 4.5))
    bp = ax.boxplot(data, tick_labels=labels, showfliers=False, patch_artist=True, whis=(5, 95))
    for patch, c in zip(bp["boxes"], colors):
        patch.set_facecolor(c); patch.set_alpha(0.5)
    for i, d in enumerate(data, 1):
        ax.text(i, np.percentile(d, 95) * 1.03, f"med {np.median(d):.0f}\np95 {np.percentile(d, 95):.0f}",
                ha="center", fontsize=7)
    ax.set_ylabel("time per decision [us]"); ax.grid(alpha=0.3, axis="y")
    ax.set_title("Session 5 - per-decision compute time (time.perf_counter around compute(), "
                 "nominal runs D+E+F, whiskers 5-95 %) - machine dependent, see results/env_info.txt",
                 fontsize=9)
    fig.tight_layout()
    fig.savefig(ctx.figs / "s5_compute_time.png", dpi=150)
    plt.close(fig)


def plot_metric_boxes(ctx, metrics):
    keys = (("arrival_time", "arrival time [s] (successes)"), ("path_length", "path length [m]"),
            ("min_guard", "min real guard [m]"), ("sum_domega", "sum |d omega| [rad/s]"))
    fig, axs = plt.subplots(len(keys), len(TEST), figsize=(15, 12))
    for j, sid in enumerate(TEST):
        for i, (k, lab) in enumerate(keys):
            data, labels, cs = [], [], []
            for sysv in SYSTEMS:
                for meth in METHODS:
                    d = [m[k] for m in metrics if m["scenario"] == sid and m["controller"] == meth
                         and m["version"] == sysv and m["condition"] == "noisy"
                         and (k != "arrival_time" or m["success"])]
                    d = [x for x in d if not (isinstance(x, float) and (math.isnan(x) or math.isinf(x)))]
                    data.append(d or [np.nan]); labels.append(f"{meth[:3]}\n{sysv[-2:]}"); cs.append(col(meth))
            bp = axs[i, j].boxplot(data, tick_labels=labels, patch_artist=True, showfliers=True)
            for patch, c in zip(bp["boxes"], cs):
                patch.set_facecolor(c); patch.set_alpha(0.5)
            axs[i, j].axvline(3.5, color="k", lw=0.6)
            axs[i, j].tick_params(labelsize=7); axs[i, j].grid(alpha=0.3, axis="y")
            if j == 0:
                axs[i, j].set_ylabel(lab, fontsize=8)
            if i == 0:
                axs[i, j].set_title(f"scenario {sid}")
            if k == "min_guard":
                axs[i, j].axhline(ctx.params.margin, color="tab:red", ls="--", lw=0.8)
    fig.suptitle(f"Session 5 - distributions over the {len(ctx.seeds)} noisy runs "
                 "(left of the line: sys-v1, right: sys-v2; red dashed = 0.15 m desired margin)")
    fig.tight_layout(rect=(0, 0, 1, 0.96))
    fig.savefig(ctx.figs / "s5_distributions.png", dpi=130)
    plt.close(fig)


def noise_ranking(ctx, agg):
    """Does noise change the ranking? Rank by (success desc, mean time asc)."""
    lines = ["Ranking per scenario: nominal vs noisy (success first, then mean time)"]
    for sysv in SYSTEMS:
        for sid in TEST:
            ranks = {}
            for cond in ("nominal", "noisy"):
                rows = [a for a in agg if a["scenario"] == sid and a["condition"] == cond
                        and a["system"] == sysv]
                rows.sort(key=lambda a: (-a["success"] / a["N"],
                                         a["T_mean"] if not math.isnan(a["T_mean"]) else 1e9))
                ranks[cond] = [a["controller"] for a in rows]
            same = "same" if ranks["nominal"] == ranks["noisy"] else "CHANGED"
            lines.append(f"  {sysv} {sid}: nominal {ranks['nominal']}  noisy {ranks['noisy']}  -> {same}")
    print("\n".join(lines))
    (ctx.results / "s5_noise_ranking.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
